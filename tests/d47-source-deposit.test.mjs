 assert.equal(m.attachment.storyArchiveId,SOURCE_FILE.id);assert.ok(archiveFile(s,SOURCE_FILE.id));assert.ok(!agent(s).jobs['server-source']);
 sendAgent(s,'',SOURCE_FILE.id);assert.equal(tearTaskInfo(s,'server-source').running,true);
