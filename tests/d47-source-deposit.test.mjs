test('Pacific accepts exact HKD deposit once and the existing delayed scene delivers Isolde receipt',t=>{
 let now=100000;t.mock.method(Date,'now',()=>now);
 const s=fixture();s.day=50;s.clock='10:00';s.story55.activeScene=null;
 for(const n of s.story55.config.nodes)if(n.day<50)s.story55.completed[n.id]={day:n.day,clock:'23:00'};
 s.content.conversations.mirage.push({id:D46_CONTACT,name:'Isolde Mirage',messages:[],unread:0});
 s.bankData.balance=1000000;
 const pay=(extra={})=>transfer(ctx(s).store,{recipient:'Isolde',account:DEPOSIT_ACCOUNT,amount:DEPOSIT_HKD,currency:'HKD',...extra});
 assert.throws(pay,/核對/);deliver(s,DEPOSIT_SCENE);s.bankData.balance=1000000;
 assert.match(renderBank(ctx(s),{route:'/transfer'}),/HKD · 港幣/);
 assert.throws(()=>pay({currency:'USD'}),/核對/);assert.equal(s.bankData.balance,1000000);
 s.bankData.balance=DEPOSIT_USD-1;assert.throws(pay,/不足/);s.bankData.balance=1000000;pay();
 assert.equal(s.bankData.balance,358974.36);assert.throws(pay);assert.equal(s.bankData.transactions.filter(t=>t.id===DEPOSIT_ID).length,1);
 assert.match(renderBank(ctx(s),{route:'/receipt/'+DEPOSIT_ID}),/HK\$5,000,000\.00/);
 const chat=s.content.conversations.mirage.find(c=>c.id===D46_CONTACT);
 now+=2999;tickQueuedStoryScenes55(s,now);assert.ok(!chat.messages.some(m=>m.text==='錢已收到。'));
 now++;tickQueuedStoryScenes55(s,now);assert.equal(chat.messages.filter(m=>m.text==='錢已收到。').length,1);
 assert.equal(s.story55.scenes[DEPOSIT_REPLY].index,1);
});
