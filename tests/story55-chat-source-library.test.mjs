test('author edits D02 source once: original lifecycle delivers revised NPC copy, not an extra message',()=>{
 const s=fresh(),source=readChatSources(s,2).find(x=>x.type==='track'&&x.lines.length&&x.lines[0].who!=='me');
 assert.ok(source);
 const edit=source.lines.map(l=>l.text);edit[0]='這是 D02 修訂過的首句';
 saveChatSource(s,source.key,{at:source.at,lines:edit});
 assert.equal(find(s,2,source.key).lines[0].text,edit[0]);
 const track=d02Track,q=track.ensure({...s,day:2,clock:'23:58'});
 const def=track.defs.find(x=>x.id===source.key.slice(4));
 assert.ok(def);
 // This track must retain its player-send gating and original stable ID.
 assert.equal(def.lines[0].text,source.lines[0].text);
 assert.deepEqual(q[def.id].started,false);
 s.day=2;s.clock='23:58';
 for(const other of track.defs)if(other.id!==def.id)q[other.id].completed=true;
 track.tick(s,100);
 track.tick(s,4000);
 const lifecycle=source.key.slice(0,3)+':'+def.id;
 const emitted=Object.values(s.content.conversations).flat().flatMap(c=>c.messages||[]).filter(m=>m.lifecycleId===lifecycle);
 assert.ok(emitted.some(m=>m.text===edit[0]));
 assert.equal(emitted.filter(m=>m.text===edit[0]).length,1);
});
