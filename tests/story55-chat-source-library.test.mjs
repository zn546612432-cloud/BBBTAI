test('author edits D02 source once: original lifecycle delivers revised NPC copy, not an extra message',()=>{
 const s=fresh(),source=readChatSources(s,2).find(x=>x.type==='track'&&x.lines.length&&x.lines[0].who!=='me');
 assert.ok(source);
 const edit=source.lines.map(l=>l.text);edit[0]='這是 D02 修訂過的首句';
 saveChatSource(s,source.key,{at:source.at,lines:edit});
 assert.equal(find(s,2,source.key).lines[0].text,edit[0]);
 const track=d02Track,q=track.ensure({...s,day:2,clock:'23:58'});
 const def=track.defs.find(x=>x.id===source.key.slice(4));
 assert.ok(def);
 // This track must retain its player-send gating and original stable ID.
 assert.equal(def.lines[0].text,source.lines[0].text);
 assert.deepEqual(q[def.id].started,false);
 s.day=2;s.clock='23:58';
 for(const other of track.defs)if(other.id!==def.id)q[other.id].completed=true;
 track.tick(s,100);
 track.tick(s,4000);
 const lifecycle=source.key.slice(0,3)+':'+def.id;
 const emitted=Object.values(s.content.conversations).flat().flatMap(c=>c.messages||[]).filter(m=>m.lifecycleId===lifecycle);
 assert.ok(emitted.some(m=>m.text===edit[0]));
 assert.equal(emitted.filter(m=>m.text===edit[0]).length,1);
});
test('D01 editable script updates both branch text and awaited player draft without auto-send',()=>{
 const s=fresh();
 const row=find(s,1,'d01:group-morning');
 const lines=row.lines.map(l=>l.text);lines[4]='我手動發出的新台詞';
 saveChatSource(s,row.key,{lines});
 assert.equal(d01GroupScript(s,'morning')[4].text,lines[4]);
 s.story55.d01??={};s.story55.d01.group={index:4,branch:'morning',started:true,awaitingPlayer:true};
 assert.equal(d01Draft(s,'group').text,lines[4]);
 assert.equal(s.content.conversations.wechat.find(c=>c.id==='group').messages.some(m=>m.text===lines[4]),false);
 assert.throws(()=>saveChatSource(s,row.key,{lines}),/本周目/);
});
test('node scene editing retains the original speaker count and never rewrites delivered player bubbles',()=>{
 const s=fresh(),source=find(s,55,'node:ending'),lines=source.lines.map(x=>x.text);
 lines[0]='編輯過的結尾';
 saveChatSource(s,source.key,{at:source.at,lines});
 assert.equal(s.story55.config.scenes.ending[0][1],lines[0]);
 const bad=source.lines.map(x=>x.text);bad.pop();
 assert.throws(()=>saveChatSource(s,source.key,{lines:bad}),/条数/);
 const old={id:'player-test',from:'me',text:'玩家真正發出的話',actual:true,day:55};
 s.content.conversations.wechat[0].messages.push(old);
 assert.equal(s.content.conversations.wechat[0].messages.at(-1).text,'玩家真正發出的話');
});
