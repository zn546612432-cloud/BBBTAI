export const dayDifference=(later,earlier)=>Math.round((Date.parse(later+'T00:00:00Z')-Date.parse(earlier+'T00:00:00Z'))/86400000);
export function visibleMoments(posts,viewerDate,{author=null,includePinned=true,clock='23:59'}={}){
 return posts.filter(post=>{
  if(author&&post.author!==author)return false;
  const days=dayDifference(viewerDate,post.publishedAt.slice(0,10));
  return post.publishedAt<=viewerDate+'T'+clock&&days>=0&&((includePinned&&post.pinned)||days<=2);
 }).sort((a,b)=>b.publishedAt.localeCompare(a.publishedAt));
}
