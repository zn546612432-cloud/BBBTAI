"""Offline music fingerprint for Tai. No API, audio upload, or assumed lyrics.

Tinggu (https://github.com/SeithAsync/Tinggu, MIT) inspired the time-axis
approach; these lightweight DSP measurements are independently implemented.
Run from repository root after replacing a bundled recording.
"""
import hashlib
import json
from pathlib import Path
import subprocess

import numpy as np
from scipy.signal import stft

ROOT = Path(__file__).resolve().parents[1]
RATE = 22050


def analyze(path):
    pcm = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ac', '1', '-ar', str(RATE), '-'])
    samples = np.frombuffer(pcm, dtype='<f4')
    freq, times, spec = stft(samples, fs=RATE, nperseg=2048, noverlap=1536)
    power = abs(spec) ** 2
    total = power.sum(axis=0) + 1e-12
    brightness = (freq[:, None] * power).sum(axis=0) / total
    bass = power[freq < 250].sum(axis=0) / total
    flux = np.maximum(0, np.diff(np.log1p(1000*abs(spec)), axis=1)).mean(axis=0)
    # Pitch-class profile of prominent spectral peaks, not a vocal transcription.
    valid = (freq >= 65) & (freq <= 4000)
    classes = np.rint(69+12*np.log2(freq[valid]/440)).astype(int)%12
    chroma = np.stack([power[valid][classes == i].sum(axis=0) for i in range(12)])
    notes = 'C C# D D# E F F# G G# A A# B'.split()
    rows = []
    for start in range(0, int(np.ceil(len(samples)/RATE)), 5):
        seg = samples[start*RATE:(start+5)*RATE]
        mask = (times >= start) & (times < start+5)
        fm = mask[1:]
        if not seg.size or not mask.any():
            continue
        profile = chroma[:,mask].mean(axis=1)
        pitches = ','.join(notes[i] for i in np.argsort(profile)[-3:][::-1])
        rows.append([start, round(float(20*np.log10(np.sqrt(np.mean(seg**2))+1e-8)),1),
                     round(float(np.median(brightness[mask]))), round(float(np.median(bass[mask]))*100),
                     round(float(np.mean(flux[fm]))*100,1) if fm.any() else 0, pitches])
    return {'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'duration': round(len(samples)/RATE, 1),
            'columns': ['seconds', 'rmsDb', 'centroidHz', 'bassPercent', 'spectralActivity', 'pitchClassPeaks'], 'windows': rows}


if __name__ == '__main__':
    files = {'melatonin': 'melatonin.mp3', 'tonight-rain': 'tonight-rain.m4a', 'where-were-going': 'where-were-going.mp3'}
    result = {key: analyze(ROOT/'public/assets/music'/filename) for key, filename in files.items()}
    target = ROOT/'src/apps/music/features/shared/listening-data.js'
    target.write_text('// Generated by scripts/analyze-music-listening.py from bundled recordings.\nexport const listeningData = '+json.dumps(result, separators=(',', ':'))+';\n', encoding='utf-8')
